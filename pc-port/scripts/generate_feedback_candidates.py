"""Freeze structurally compatible game compute hashes into a PC-native registry.

The source catalog is an offline SPIR-V scan. Membership never authorizes
replacing a dispatch: runtime must also prove a 48-byte record and its aliases.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "gpu/infamous_renderer/generated_feedback_candidates.h"
MANIFEST = ROOT / "gpu/infamous_renderer/generated_feedback_candidates.json"
KNOWN_STRIDES = {0x3EA96DB0: 64, 0x63E538C1: 80, 0x9C58AA06: 112}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--catalog", type=Path, required=True)
    args = ap.parse_args()
    data = json.loads(args.catalog.read_text(encoding="utf-8"))
    if data["examined_spv_files"] != 2992 or data["malformed"]:
        raise ValueError("catalog identity/validation changed; re-audit")
    by_hash: dict[int, tuple[int, int]] = {}
    for row in data["direct_binding0_atomic_add_word1_candidates"]:
        name = row["file"]
        hash_value = int(name.split("_", 1)[0], 16)
        mask = 0
        for word_text, opcodes in row["atomic_ops_by_word"].items():
            word = int(word_text)
            if word >= 16:
                raise ValueError("atomic word index exceeds compact mask")
            if opcodes:
                mask |= 1 << word
        if not mask & (1 << 1):
            raise ValueError("candidate lacks word-1 atomic")
        entry = (mask, KNOWN_STRIDES.get(hash_value, 0))
        if hash_value in by_hash and by_hash[hash_value] != entry:
            raise ValueError(f"variants disagree for {hash_value:016x}")
        by_hash[hash_value] = entry
    if len(by_hash) != 351:
        raise ValueError(f"unexpected unique candidate count {len(by_hash)}")
    source_sha = hashlib.sha256(args.catalog.read_bytes()).hexdigest()
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by pc-port/scripts/generate_feedback_candidates.py.",
        f"// Source catalog SHA-256: {source_sha}",
        "// Structural filter only; not proof of a 48-byte runtime record.",
        "#pragma once",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace iss::game::feedback {",
        "struct AtomicCandidate {",
        "    std::uint64_t shader_hash;",
        "    std::uint16_t atomic_word_mask;",
        "    std::uint16_t known_output_stride_bytes; // zero means unproven",
        "};",
        f"inline constexpr std::array<AtomicCandidate, {len(by_hash)}> AtomicCandidates{{{{",
    ]
    for shader_hash, (mask, stride) in sorted(by_hash.items()):
        lines.append(f"    {{0x{shader_hash:016X}ULL, 0x{mask:04X}, {stride}}},")
    lines.extend([
        "}};",
        "[[nodiscard]] constexpr const AtomicCandidate* FindAtomicCandidate(",
        "    std::uint64_t hash) noexcept {",
        "    std::size_t lo = 0, hi = AtomicCandidates.size();",
        "    while (lo < hi) {",
        "        const auto mid = lo + (hi - lo) / 2;",
        "        if (AtomicCandidates[mid].shader_hash < hash) lo = mid + 1;",
        "        else hi = mid;",
        "    }",
        "    return lo < AtomicCandidates.size() && AtomicCandidates[lo].shader_hash == hash",
        "        ? &AtomicCandidates[lo] : nullptr;",
        "}",
        "} // namespace iss::game::feedback",
        "",
    ])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    manifest = {"schema": "iss.feedback-atomic-candidates.v1",
                "source_catalog": args.catalog.name,  # the file name only: no local paths in the repository
                "source_sha256": source_sha,
                "examined_spv_files": data["examined_spv_files"],
                "candidate_variants": len(data["direct_binding0_atomic_add_word1_candidates"]),
                "unique_hashes": len(by_hash),
                "generated_header_sha256": hashlib.sha256(OUTPUT.read_bytes()).hexdigest(),
                "known_output_strides": {f"0x{k:08X}": v for k, v in KNOWN_STRIDES.items()},
                "runtime_use": "structural filter only; descriptor/address/alias checks required"}
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
